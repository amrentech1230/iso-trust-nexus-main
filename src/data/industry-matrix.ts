export function industryMatrixIncludesStandard(terms: string[], standardCode: string) {
  const code = standardCode.match(/\d{4,5}(?:-\d)?/)?.[0];
  if (!code) return false;

  const escapedCode = code.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const codePattern = new RegExp(`(^|\\D)${escapedCode}(?=\\D|$)`);
  return terms.some(
    (term) =>
      !term.startsWith("Training: ") && codePattern.test(term.replace(/^Certification: /, "")),
  );
}
